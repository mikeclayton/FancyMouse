using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace FancyMouse.Win32Gen.Generators;

/// <summary>
/// Shared plumbing for <see cref="Win32FrameworkGenerator"/> and
/// <see cref="Win32FunctionGenerator"/> - each is its own
/// <see cref="IIncrementalGenerator"/> (so each kind of generated output -
/// framework types, api wrappers - is independently decoupled and can be
/// reasoned about on its own), but both still emit into the same single
/// <c>{RootNamespace}.Win32Gen</c> namespace, so a consuming project only
/// ever needs one <c>using</c> to see all of it. Only the generated
/// *files* are organised into separate folders (Framework/Functions) for
/// on-disk navigability.
/// </summary>
internal static class Win32GeneratorHelpers
{
    private const string DefaultRootNamespace = "GeneratedWin32Interop";
    private const string NamespaceSuffix = "Win32Gen";

    public static IncrementalValueProvider<string> GetRootNamespace(IncrementalGeneratorInitializationContext context)
        => context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) => Win32GeneratorHelpers.ResolveRootNamespace(options));

    public static string BuildFrameworkFileSource(string rootNamespace, string fragment)
    {
        // the fragment's own using directives go *above* the namespace declaration, the same
        // as BuildClassSource's - a using placed after a file-scoped namespace is resolved
        // relative to that namespace, so in a project whose namespace has a "Windows" segment
        // (e.g. FancyMouse.Windows) "using Windows.Win32.Foundation;" would bind to the
        // project's own namespace instead of CsWin32's Windows.Win32, and fail to compile
        Win32GeneratorHelpers.SplitLeadingUsings(fragment, out var usings, out var body);
        var usingsBlock = (usings.Length == 0) ? string.Empty : usings + "\n\n";

        return $$"""
            // <auto-generated/>
            #nullable enable

            {{usingsBlock}}namespace {{rootNamespace}}.{{Win32GeneratorHelpers.NamespaceSuffix}};

            {{body}}

            """;
    }

    /// <param name="win32TypeNames">
    /// Fully qualified names of the CsWin32 types the wrapped api's signatures use (see
    /// <c>CsWin32Methods.GetWin32TypeNames</c>) - each one gets a
    /// <c>using {Name} = global::{FullName};</c> alias so the templates can use the simple name.
    /// </param>
    /// <remarks>
    /// Aliases for the specific *types* rather than <c>using</c>s for their namespaces: CsWin32
    /// only generates the namespaces a project's own NativeMethods.txt actually needs, so a
    /// fixed list of namespace usings breaks (CS0234) in any project that doesn't happen to
    /// request something from every one of them - whereas every type in an api's own signature
    /// is guaranteed to exist, because CsWin32 had to generate it to declare that api.
    /// <c>Windows.Win32</c> itself always exists too, since that's where <c>PInvoke</c> lives.
    /// </remarks>
    public static string BuildClassSource(string rootNamespace, string className, IEnumerable<ApiWrapperTemplate> templates, IEnumerable<string> win32TypeNames)
    {
        var methods = string.Join("\n\n", templates.Select(template => Win32GeneratorHelpers.Indent(template.MethodSource)));

        var aliases = string.Join(
            "\n",
            win32TypeNames.Select(fullName => $"using {Win32GeneratorHelpers.GetSimpleTypeName(fullName)} = global::{fullName};"));
        var aliasesBlock = (aliases.Length == 0) ? string.Empty : aliases + "\n\n";

        return $$"""
            // <auto-generated/>
            #nullable enable

            using System.Drawing;
            using System.Runtime.InteropServices;

            using Windows.Win32;

            {{aliasesBlock}}namespace {{rootNamespace}}.{{Win32GeneratorHelpers.NamespaceSuffix}};

            internal static partial class {{className}}
            {
            {{methods}}
            }

            """;
    }

    /// <summary>
    /// The last segment of a fully qualified type name - e.g. <c>HWND</c> for
    /// <c>Windows.Win32.Foundation.HWND</c>.
    /// </summary>
    public static string GetSimpleTypeName(string fullName)
        => fullName.Substring(fullName.LastIndexOf('.') + 1);

    private static string ResolveRootNamespace(AnalyzerConfigOptionsProvider options)
        => options.GlobalOptions.TryGetValue("build_property.RootNamespace", out var value) && !string.IsNullOrEmpty(value)
            ? value
            : Win32GeneratorHelpers.DefaultRootNamespace;

    private static string Indent(string source)
    {
        var lines = source.Replace("\r\n", "\n").Trim('\n').Split('\n');
        return string.Join("\n", lines.Select(line => line.Length == 0 ? line : "    " + line));
    }

    /// <summary>
    /// Splits <paramref name="source"/> into its leading block of using directives (including
    /// any blank lines between groups of them) and everything after it.
    /// </summary>
    private static void SplitLeadingUsings(string source, out string usings, out string body)
    {
        var lines = source.Replace("\r\n", "\n").Split('\n');

        var index = 0;
        while ((index < lines.Length)
            && ((lines[index].Trim().Length == 0) || lines[index].TrimStart().StartsWith("using ", StringComparison.Ordinal)))
        {
            index++;
        }

        usings = string.Join("\n", lines.Take(index)).Trim('\n');
        body = string.Join("\n", lines.Skip(index)).Trim('\n');
    }
}
